export function translateUiText(value: string, language: UiLanguage): string {
  if (language !== "en" || !value.trim()) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const normalized = value.trim();
  const direct = EN_UI_TEXT[normalized];
  if (direct) return `${leading}${direct}${trailing}`;
  for (const [pattern, render] of DYNAMIC_TRANSLATIONS) {
    const matches = normalized.match(pattern);
    if (matches) return `${leading}${render(...matches)}${trailing}`;
  }
  return value;
}

type UiLanguageContextValue = {
  language: UiLanguage;
  setLanguage: (language: UiLanguage) => void;
};

const UiLanguageContext = createContext<UiLanguageContextValue>({
  language: "zh-CN",
  setLanguage: () => undefined,
});

function initialLanguage(): UiLanguage {
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "en" ? "en" : "zh-CN";
}

export function UiLanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<UiLanguage>(initialLanguage);
  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);
  return <UiLanguageContext.Provider value={{ language, setLanguage }}>{children}</UiLanguageContext.Provider>;
}

export function useUiLanguage() {
  return useContext(UiLanguageContext);
}

const TRANSLATABLE_ATTRIBUTES = ["placeholder", "title", "aria-label"] as const;

export function LocalizedSurface({ children }: { children: ReactNode }) {
  const { language } = useUiLanguage();
  const rootRef = useRef<HTMLDivElement>(null);
  const originalText = useRef(new WeakMap<Text, string>());
  const originalAttributes = useRef(new WeakMap<Element, Map<string, string>>());

  useLayoutEffect(() => {
    const root = rootRef.current;
    if (!root) return;

    function localizeTextNode(node: Text) {
      const current = node.nodeValue ?? "";
      const original = originalText.current.get(node);
      if (language === "zh-CN") {
        if (original !== undefined && current !== original) node.nodeValue = original;
        originalText.current.delete(node);
        return;
      }
      if (original !== undefined && current === translateUiText(original, "en")) return;
      const source = original !== undefined && current === original ? original : current;
      const translated = translateUiText(source, "en");
      if (translated !== source) {
        originalText.current.set(node, source);
        node.nodeValue = translated;
      }
    }

    function localizeElement(element: Element) {
      for (const attribute of TRANSLATABLE_ATTRIBUTES) {
        const current = element.getAttribute(attribute);
        if (current === null) continue;
        const originals = originalAttributes.current.get(element);
        const original = originals?.get(attribute);
        if (language === "zh-CN") {
          if (original !== undefined && current !== original) element.setAttribute(attribute, original);
          originals?.delete(attribute);
          continue;
        }
        if (original !== undefined && current === translateUiText(original, "en")) continue;
        const source = original !== undefined && current === original ? original : current;
        const translated = translateUiText(source, "en");
        if (translated !== source) {
          const nextOriginals = originals ?? new Map<string, string>();
          nextOriginals.set(attribute, source);
          originalAttributes.current.set(element, nextOriginals);
          element.setAttribute(attribute, translated);
        }
      }
    }

    function localizeTree(start: Node) {
      if (start.nodeType === Node.TEXT_NODE) localizeTextNode(start as Text);
      if (start.nodeType === Node.ELEMENT_NODE) localizeElement(start as Element);
      const walker = document.createTreeWalker(start, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
      let node = walker.nextNode();
      while (node) {
        if (node.nodeType === Node.TEXT_NODE) localizeTextNode(node as Text);
        else localizeElement(node as Element);
        node = walker.nextNode();
      }
    }

    localizeTree(root);
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData") localizeTextNode(mutation.target as Text);
        if (mutation.type === "attributes") localizeElement(mutation.target as Element);
        mutation.addedNodes.forEach(localizeTree);
      }
    });
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...TRANSLATABLE_ATTRIBUTES] });
    return () => observer.disconnect();
  }, [language]);

  return <div className="localized-surface" ref={rootRef}>{children}</div>;
}
